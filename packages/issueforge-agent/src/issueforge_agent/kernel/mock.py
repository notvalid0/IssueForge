from __future__ import annotations

import hashlib
import json
from pathlib import Path

from issueforge_core.ncu import synthetic_metrics


class MockBackend:
    """无 GPU 的可运行后端：生成/评测/NCU 都是确定性的模拟数据。

    它让 Agent 状态机、RAG、数据库和 Dashboard 在没有 CUDA 的机器上也能完整跑通。
    """

    name = "mock"

    def __init__(self, gpu: str = "Mock H100", work_dir: Path | None = None):
        self.gpu = gpu
        self.work_dir = work_dir or Path(".")
        self._round = 0

    def prepare(self, task_path: Path) -> dict:
        text = task_path.read_text(encoding="utf-8", errors="ignore") if task_path.exists() else ""
        return {
            "task_name": task_path.stem,
            "reference": text,
            "gpu": self.gpu,
            "backend": self.name,
        }

    def generate(self, prompt: str, phase: str, round_index: int, current_code: str = "") -> str:
        seed = int(hashlib.sha256(f"{prompt[:500]}:{round_index}".encode()).hexdigest()[:8], 16)
        variant = seed % 4
        return f'''# mock kernel generated by IssueForge ({phase}, round {round_index})
import torch
from torch.utils.cpp_extension import load_inline

source = r"""
#include <torch/extension.h>
#include <cuda_runtime.h>

__global__ void mock_kernel(const float* x, float* y, int n) {{
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) {{
        y[i] = x[i] * 2.0f;
    }}
}}

torch::Tensor mock_forward(torch::Tensor x) {{
    auto y = torch::empty_like(x);
    int n = x.numel();
    mock_kernel<<<(n + 255) / 256, 256>>>(x.data_ptr<float>(), y.data_ptr<float>(), n);
    return y;
}}
"""

cpp_src = "torch::Tensor mock_forward(torch::Tensor x);"

_ext = load_inline(
    name="issueforge_mock_{round_index}_{variant}",
    cpp_sources=cpp_src,
    cuda_sources=source,
    functions=["mock_forward"],
    verbose=False,
)

class ModelNew(torch.nn.Module):
    def forward(self, x):
        return _ext.mock_forward(x)
'''

    def evaluate(self, code: str, task_path: Path, round_index: int, work_dir: Path | None = None) -> dict:
        # 模拟：第 0 轮是基线，之后稳定提升；偶尔有一次小回退，方便观察 best-so-far。
        base = 1.0
        gain = 0.12 * round_index + 0.03 * (len(code) % 7)
        if round_index == 4:
            gain *= 0.4
        speedup = round(base + gain, 4)
        ref_ms = 2.4
        test_ms = round(ref_ms / speedup, 4)
        return {
            "runnable": True,
            "score": speedup,
            "ref_latency_ms": {"avg": ref_ms, "min": ref_ms * 0.96, "max": ref_ms * 1.04},
            "test_latency_ms": {"avg": test_ms, "min": test_ms * 0.96, "max": test_ms * 1.04},
            "phase": "mock",
            "backend": self.name,
        }

    def profile(self, code: str, task_path: Path, round_index: int, speedup: float = 1.0, work_dir: Path | None = None) -> dict:
        return synthetic_metrics(round_index, speedup)

    def health(self) -> dict:
        return {"ok": True, "backend": self.name, "gpu": self.gpu, "note": "mock 模式，不需要 GPU"}

    def write_code(self, code: str, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(code, encoding="utf-8")
        return path

    def summary(self, code: str, metrics: dict) -> dict:
        return json.loads(json.dumps(metrics, ensure_ascii=False))
